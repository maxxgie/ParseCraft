"""Generate a standalone, runnable LR parser from an analysis.

The generated module embeds the ACTION/GOTO tables and the numbered
productions of a grammar and implements the classic table-driven LR parsing
loop, so the user can take a grammar and get a working parser program.
"""

from __future__ import annotations

from typing import List, Optional

from core.logging_config import get_logger
from core.table_builder import assign_production_numbers

logger = get_logger(__name__)

_TEMPLATE_HEADER = '''"""Auto-generated LR parser.

Generated by the Bottom-Up Parser Simulator.
Do not edit by hand; regenerate from the grammar instead.
"""

'''


def _action_literal(action) -> Optional[str]:
    """Return the Python literal for a table action, or ``None`` to skip."""
    if action.action_type == "shift":
        return repr(("s", action.state))
    if action.action_type == "reduce":
        return repr(("r", action.rule_number))
    if action.action_type == "accept":
        return repr(("acc", 0))
    return None


def _format_dict(name: str, entries: List[str]) -> List[str]:
    """Format a Python dict literal from pre-rendered ``key: value`` lines."""
    if not entries:
        return [f"{name} = {{}}"]
    lines = [f"{name} = {{"]
    lines.extend(entries)
    lines.append("}")
    return lines


def generate_lr_parser(
    analysis,
    class_name: str = "LRParser",
    sample_input: Optional[List[str]] = None,
) -> str:
    """Generate Python source for a table-driven LR parser.

    Args:
        analysis: An :class:`~core.engine.AnalysisResult`.
        class_name: Name of the generated parser class.
        sample_input: Optional token list used in the ``__main__`` demo.

    Returns:
        A string containing a complete, runnable Python module.
    """
    table = analysis.table
    grammar = analysis.grammar
    _numbers, rules = assign_production_numbers(grammar)

    action_entries: List[str] = []
    for (state, terminal), action in sorted(table.action.items()):
        literal = _action_literal(action)
        if literal is None:
            continue
        action_entries.append(f"    ({state}, {terminal!r}): {literal},")

    goto_entries: List[str] = []
    for (state, non_terminal), target in sorted(table.goto.items()):
        goto_entries.append(f"    ({state}, {non_terminal!r}): {target},")

    production_entries: List[str] = []
    for index, (lhs, rhs) in enumerate(rules):
        production_entries.append(
            f"    {index}: ({lhs!r}, {tuple(rhs)!r}),  # R{index}"
        )

    if sample_input is None:
        sample_input = ["id"]

    lines: List[str] = []
    lines.append(_TEMPLATE_HEADER)
    lines.append(f"# Productions: index -> (lhs, rhs tuple); rule 0 is augmented.")
    lines.extend(_format_dict("PRODUCTIONS", production_entries))
    lines.append("")
    lines.append("# ACTION table: (state, terminal) -> action tuple")
    lines.extend(_format_dict("ACTION", action_entries))
    lines.append("")
    lines.append("# GOTO table: (state, non_terminal) -> state")
    lines.extend(_format_dict("GOTO", goto_entries))
    lines.append("")
    lines.append("")
    lines.append("def tokenize(text):")
    lines.append('    """Split an input string into whitespace-separated tokens."""')
    lines.append("    return text.split()")
    lines.append("")
    lines.append("")
    lines.append(f"class {class_name}:")
    lines.append('    """Table-driven LR parser."""')
    lines.append("")
    lines.append("    PRODUCTIONS = PRODUCTIONS")
    lines.append("    ACTION = ACTION")
    lines.append("    GOTO = GOTO")
    lines.append("")
    lines.append("    def __init__(self):")
    lines.append("        self.trace = []")
    lines.append("")
    lines.append("    def parse(self, tokens):")
    lines.append('        """Parse tokens. Return True on accept, False otherwise.')
    lines.append("")
    lines.append("        The reduction/shift trace is available in ``self.trace``.")
    lines.append('        """')
    lines.append("        stack = [0]")
    lines.append("        symbols = []")
    lines.append("        tokens = list(tokens) + ['$']")
    lines.append("        i = 0")
    lines.append("        while True:")
    lines.append("            state = stack[-1]")
    lines.append("            lookahead = tokens[i]")
    lines.append("            action = self.ACTION.get((state, lookahead))")
    lines.append("            if action is None:")
    lines.append("                self.trace.append(('error', state, lookahead))")
    lines.append("                return False")
    lines.append("            kind = action[0]")
    lines.append("            if kind == 's':")
    lines.append("                stack.append(action[1])")
    lines.append("                symbols.append(lookahead)")
    lines.append("                self.trace.append(('shift', lookahead, action[1]))")
    lines.append("                i += 1")
    lines.append("            elif kind == 'r':")
    lines.append("                rule = action[1]")
    lines.append("                lhs, rhs = self.PRODUCTIONS[rule]")
    lines.append("                n = len(rhs)")
    lines.append("                if n:")
    lines.append("                    del stack[-n:]")
    lines.append("                    del symbols[-n:]")
    lines.append("                goto = self.GOTO.get((stack[-1], lhs))")
    lines.append("                if goto is None:")
    lines.append("                    return False")
    lines.append("                stack.append(goto)")
    lines.append("                symbols.append(lhs)")
    lines.append("                self.trace.append(('reduce', rule, lhs, rhs))")
    lines.append("            elif kind == 'acc':")
    lines.append("                self.trace.append(('accept',))")
    lines.append("                return True")
    lines.append("            else:")
    lines.append("                return False")
    lines.append("")
    lines.append("")
    lines.append("if __name__ == '__main__':")
    lines.append(f"    parser = {class_name}()")
    lines.append(f"    demos = [{sample_input!r}]")
    lines.append("    for tokens in demos:")
    lines.append("        ok = parser.parse(tokens)")
    lines.append("        print(' '.join(tokens), '->', 'ACCEPT' if ok else 'REJECT')")
    lines.append("        for step in parser.trace:")
    lines.append("            print('   ', step)")
    lines.append("")

    code = "\n".join(lines)
    logger.info("Generated LR parser code (%d lines)", len(lines))
    return code